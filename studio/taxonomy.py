def get_main_tags() -> list[dict[str, Any]]:
    """获取 17 个核心主 Tags 清单（含 ID、中文名、描述、图标）。"""
    return MAIN_TAGS


def match_best_pattern(text: str) -> str | None:
    """
    在正则中取「语义最长命中」者。分两轮：
      1) 先只在主体类 TAG 中取最长命中；
      2) 主体类一个都没命中时，才在风格/属性类 TAG (Art/Fantasy/Colors/Composition) 中取。
    即：风格 TAG 优先级最低，只要能匹配到任何主体 TAG，就不会归到风格 TAG。
    """
    best_len = -1
    best_tag: str | None = None
    style_len = -1
    style_tag: str | None = None
    for main_tag, compiled in _COMPILED_PATTERNS.items():
        if main_tag == "Others":
            continue
        for pat, weight in compiled:
            if not pat.search(text):
                continue
            if main_tag in _STYLE_TAGS:
                if weight > style_len:
                    style_len = weight
                    style_tag = main_tag
            elif weight > best_len:
                best_len = weight
                best_tag = main_tag
    return best_tag or style_tag


def normalize_tag(tag: str | None) -> str:
    """
    将任意输入的字符串标签归一化为标准的 17 主 Tag ID 之一。
    匹配顺序: 中文别名 -> 历史 cat_ 前缀 -> 主 Tag 全等 -> 全词精确表 -> 正则最长命中。
    例如:
      'cats' -> 'Pets'
      'mountains' -> 'Landscapes'
      'christmas_tree' -> 'Holidays'   (精确表整串命中, 不再被 tree 抢走)
      'oil_painting' -> 'Art'          (最长命中, 不再被 painting 抢走)
      'anime_girl' -> 'People'         (主体 TAG 优先于风格 TAG)
      '猫咪' -> 'Pets'
      'Unknown' -> 'Others'
    """
    if not tag:
        return "Others"

    cleaned = str(tag).strip()
    if not cleaned:
        return "Others"

    # 1. 检查中文别名映射
    if cleaned in _ZH_ALIAS_MAP:
        return _ZH_ALIAS_MAP[cleaned]

    # 2. 检查是否带历史 cat_ 前缀
    lower_cleaned = cleaned.lower()
    if lower_cleaned in _LEGACY_CAT_MAP:
        return _LEGACY_CAT_MAP[lower_cleaned]

    # 3. 检查直接匹配主 Tag (大小写不敏感)
    for main_tag in MAIN_TAG_IDS:
        if lower_cleaned == main_tag.lower():
            return main_tag

    # 4. 全词精确匹配 (目录名整串命中, 支持空格/连字符归一与单复数回退)
    key = re.sub(r"[\s\-]+", "_", lower_cleaned)
    hit = _exact_lookup(key) or _exact_lookup(key.replace("_", ""))
    if hit:
        return hit

    # 5. 正则子串匹配: 取语义最长命中者
    return match_best_pattern(cleaned) or "Others"


def normalize_tags(tags: list[str] | None) -> list[str]:
    """
    将标签列表逐一归一化，去重并保持原始顺序。若全部无法匹配则返回 ['Others']。
    """
    if not tags:
        return ["Others"]

    result: list[str] = []
    seen: set[str] = set()

    for t in tags:
        norm = normalize_tag(t)
        if norm not in seen:
            seen.add(norm)
            result.append(norm)

    return result if result else ["Others"]


def infer_tags_from_path(path: str | Path, root: Path | None = None) -> list[str]:
    """
    从图片文件的路径语义（优先最内层父目录名）智能推断应赋予的主 Tags。
    规则：严格从各级父目录名识别，绝不从文件名推断（避免文件名随机命名导致误判）。
    """
    p = Path(path)

    # 如果有 root 且属于 root 下的子路径，取相对路径解析
    if root is not None:
        try:
            p = p.relative_to(root)
        except Exception as e:
            logger.debug("路径不属于 root，按原路径处理: %s (%s)", p, e)

    # 目录层级（从最靠近文件的父目录向上遍历）
    parent_dirs = list(p.parts[:-1]) if len(p.parts) > 1 else []

    # 1. 优先从最靠近文件的父目录开始识别
    for d in reversed(parent_dirs):
        norm = normalize_tag(d)
        if norm != "Others":
            return [norm]

    # 2. 回退为祖先目录名做正则最长命中（不检查文件名，避免文件名随机字符串造成误判）
    for d in reversed(parent_dirs):
        best = match_best_pattern(d)
        if best:
            return [best]

    return ["Others"]


def suggest_tags_for_image(filename: str, parent_dirs: list[str] | None = None) -> list[str]:
    """基于文件名和父目录列表推荐标签。若有父目录优先从目录识别，无目录时才从文件名识别。"""
    if parent_dirs:
        for d in reversed(parent_dirs):
            norm = normalize_tag(d)
            if norm != "Others":
                return [norm]
    stem = Path(filename).stem
    norm = normalize_tag(stem)
    return [norm]


