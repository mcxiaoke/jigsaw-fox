def _extract_word(pattern: str) -> str | None:
    """从正则中反解出可整串精确匹配的裸词；无法反解则返回 None。"""
    s = pattern
    if s.startswith(r"(?<![a-z])") and s.endswith(r"(?![a-z])"):
        s = s[len(r"(?<![a-z])"):-len(r"(?![a-z])")]
        if s.endswith("s?"):
            s = s[:-2]
    elif s.startswith("^") and s.endswith("$"):
        s = s[1:-1]
        if s.endswith("s?"):
            s = s[:-2]
    elif s.endswith(r"\b"):
        s = s[:-2]
    return s if re.fullmatch(r"[a-z_]+", s) else None


def _build_exact_map() -> dict[str, str]:
    """按主标签顺序构建裸词 -> 标签 的精确表（先出现者优先）。"""
    table: dict[str, str] = {}
    for tag, patterns in TAG_PATTERNS.items():
        if tag == "Others":
            continue
        for pattern in patterns:
            word = _extract_word(pattern)
            if word and word not in table:
                table[word] = tag
    return table


EXACT_MAP: dict[str, str] = _build_exact_map()
_EXACT_MAP = EXACT_MAP


def _exact_lookup(key: str) -> str | None:
    """整串精确查表，带单复数回退。"""
    if key in _EXACT_MAP:
        return _EXACT_MAP[key]
    if key.endswith("s") and key[:-1] in _EXACT_MAP:
        return _EXACT_MAP[key[:-1]]
    if key.endswith("es") and key[:-2] in _EXACT_MAP:
        return _EXACT_MAP[key[:-2]]
    if key.endswith("ies") and (key[:-3] + "y") in _EXACT_MAP:
        return _EXACT_MAP[key[:-3] + "y"]
    if (key + "s") in _EXACT_MAP:
        return _EXACT_MAP[key + "s"]
    return None


